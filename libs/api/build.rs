//! Generates `ViSyscall`, its `From<usize>` raw-id decode and `allowlist_bit`
//! from `abi/syscalls.toml` (architecture remediation Phase 08, Law-1 CP1).
//!
//! The table is the single source; numbers and bits are frozen and pinned by
//! `abi/syscalls.golden.json` through the kernel host test `syscall_golden`.
//! The parser accepts exactly the subset the table uses: `[[syscall]]` rows,
//! `key = integer`, `key = "string"` and `key = '''` multi-line literal strings,
//! and `#` comment lines. Anything else fails the build.

use std::fmt::Write as _;
use std::path::Path;

#[derive(Default)]
struct Row {
    name: String,
    number: Option<usize>,
    bit: Option<u8>,
    doc: Vec<String>,
    bit_note: Vec<String>,
}

fn parse(text: &str) -> Vec<Row> {
    let mut rows: Vec<Row> = Vec::new();
    let mut lines = text.lines().enumerate();
    while let Some((n, line)) = lines.next() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if line == "[[syscall]]" {
            rows.push(Row::default());
            continue;
        }
        let (key, value) = line
            .split_once(" = ")
            .unwrap_or_else(|| panic!("syscalls.toml:{}: expected `key = value`", n + 1));
        let row = rows
            .last_mut()
            .unwrap_or_else(|| panic!("syscalls.toml:{}: key before [[syscall]]", n + 1));
        let text_value = if value == "'''" {
            let mut body = Vec::new();
            loop {
                let (_, l) = lines
                    .next()
                    .unwrap_or_else(|| panic!("syscalls.toml:{}: unterminated '''", n + 1));
                if l == "'''" {
                    break;
                }
                body.push(l.to_string());
            }
            Some(body)
        } else {
            None
        };
        match key {
            "name" => row.name = value.trim_matches('"').to_string(),
            "number" => row.number = Some(value.parse().expect("number")),
            "bit" => row.bit = Some(value.parse().expect("bit")),
            "doc" => row.doc = text_value.expect("doc is a ''' string"),
            "bit_note" => row.bit_note = text_value.expect("bit_note is a ''' string"),
            // Documentation-only fields of the table.
            "group" | "group_note" | "comment" => {}
            other => panic!("syscalls.toml:{}: unknown key `{other}`", n + 1),
        }
    }
    rows
}

fn doc_lines(out: &mut String, indent: &str, lines: &[String]) {
    for l in lines {
        if l.is_empty() {
            writeln!(out, "{indent}///").unwrap();
        } else {
            writeln!(out, "{indent}/// {l}").unwrap();
        }
    }
}

fn generate(rows: &[Row]) -> String {
    let mut out = String::new();
    out.push_str(
        "// @generated by libs/api/build.rs from libs/api/abi/syscalls.toml — do not edit.\n\n",
    );
    out.push_str(
        "/// System Call Identifiers (The Contract)\n///\n\
         /// These IDs must match between Kernel and User (libs/ostd). Generated from\n\
         /// `libs/api/abi/syscalls.toml`; numbers are frozen (Law 1).\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n#[repr(usize)]\npub enum ViSyscall {\n",
    );
    let mut seen_numbers = std::collections::BTreeSet::new();
    let mut seen_names = std::collections::BTreeSet::new();
    for row in rows {
        let number = row
            .number
            .unwrap_or_else(|| panic!("{}: no number", row.name));
        assert!(seen_numbers.insert(number), "duplicate number {number}");
        assert!(
            seen_names.insert(row.name.clone()),
            "duplicate name {}",
            row.name
        );
        doc_lines(&mut out, "    ", &row.doc);
        writeln!(out, "    {} = {number},", row.name).unwrap();
    }
    out.push_str("}\n\nimpl ViSyscall {\n");
    out.push_str(
        "    /// Stable bit index for the per-Cell syscall allowlist stored in\n\
         \x20   /// `Task::syscall_allowlist`.\n    ///\n\
         \x20   /// Bit indices are independent of raw opcode values so they remain stable\n\
         \x20   /// even if opcodes are renumbered.  Returns `None` for syscalls that are\n\
         \x20   /// always permitted (Yield, Exit) — filtering them would prevent a Cell\n\
         \x20   /// from ever yielding or cleanly shutting down. The reason for each\n\
         \x20   /// unbitted or shared bit is the row's `bit_note` in the table.\n    ///\n\
         \x20   /// Bit 36 is reserved for raw block-I/O syscalls (opcodes 500-503) which\n\
         \x20   /// bypass `ViSyscall::from()` and must be checked separately at dispatch.\n\
         \x20   pub const fn allowlist_bit(self) -> Option<u8> {\n        match self {\n",
    );
    for row in rows {
        for note in &row.bit_note {
            writeln!(out, "            // {note}").unwrap();
        }
        match row.bit {
            Some(bit) => writeln!(out, "            Self::{} => Some({bit}),", row.name),
            None => writeln!(out, "            Self::{} => None,", row.name),
        }
        .unwrap();
    }
    out.push_str("        }\n    }\n}\n\nimpl From<usize> for ViSyscall {\n");
    out.push_str("    fn from(id: usize) -> Self {\n        match id {\n");
    for row in rows.iter().filter(|r| r.name != "Unknown") {
        writeln!(
            out,
            "            {} => ViSyscall::{},",
            row.number.expect("number"),
            row.name
        )
        .unwrap();
    }
    out.push_str("            _ => ViSyscall::Unknown,\n        }\n    }\n}\n");
    out
}

fn main() {
    // printf.c is not yet compiled into the crate (cc build is disabled).
    // These rerun-if directives ensure the build script re-runs if C sources change.
    println!("cargo:rerun-if-changed=src/c/printf.c");
    println!("cargo:rerun-if-changed=src/c/printf.h");

    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let table = Path::new(&manifest).join("abi/syscalls.toml");
    println!("cargo:rerun-if-changed={}", table.display());
    let text = std::fs::read_to_string(&table).expect("read abi/syscalls.toml");
    let rows = parse(&text);
    assert!(
        rows.iter().any(|r| r.name == "Unknown"),
        "the table must keep the Unknown sentinel row"
    );
    let out = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("syscall_table.rs");
    std::fs::write(out, generate(&rows)).expect("write syscall_table.rs");
}
