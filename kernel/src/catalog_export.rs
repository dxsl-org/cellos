//! Export of [`crate::catalog`] to `scripts/catalog.generated.json`.
//!
//! The policy signer (`scripts/sign-policy.py`) and the catalog cross-check
//! (`scripts/check-catalog.py`) read this file instead of parsing kernel source.
//! The test fails when the committed file differs from the production catalog;
//! `CELLOS_CATALOG_WRITE=1 cargo test -p cellos-kernel --features compile-only
//! --target x86_64-unknown-linux-gnu catalog_export` rewrites it. Run without
//! fixture features so only production rows are exported.

use crate::catalog::{self, Cell};
use crate::task::cap::CapSet;
use crate::task::drivers::pcie_ecam::ETHERNET_DRIVER_IDS;
use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;

fn caps(c: &CapSet) -> String {
    let flags = [
        ("block_io", c.block_io),
        ("network", c.network),
        ("spawn", c.spawn),
        ("hypervisor", c.hypervisor),
        ("pcie_driver", c.pcie_driver),
        ("platform", c.platform),
        ("supervisor", c.supervisor),
        ("usb_driver", c.usb_driver),
        ("serial_port", c.serial_port),
        ("net_resolve", c.net_resolve),
        ("net_connect", c.net_connect),
        ("net_listen", c.net_listen),
        ("net_l2", c.net_l2),
        ("observe_tasks", c.observe_tasks),
        ("observe_memory", c.observe_memory),
        ("vfs_mutate", c.vfs_mutate),
        ("config_write", c.config_write),
        ("kms_ssh_sign", c.kms_ssh_sign),
        ("kms_ssh_admin", c.kms_ssh_admin),
    ];
    let mut out = String::from("{");
    for (name, value) in flags {
        out += &format!("\"{name}\": {value}, ");
    }
    out += &format!(
        "\"mmio_devices\": {}, \"block_regions\": {}}}",
        c.mmio_devices, c.block_regions
    );
    out
}

fn opt(c: Option<CapSet>) -> String {
    c.map_or(String::from("null"), |c| caps(&c))
}

fn row(cell: &Cell) -> String {
    let path = cell.path;
    format!(
        "    {{\n      \"path\": \"{path}\",\n      \"request\": {},\n      \"ptrust\": {},\n      \"boot\": {},\n      \"user_target\": {},\n      \"trusted_core\": {}\n    }}",
        caps(&catalog::request(path)),
        CapSet::path_mints_ptrust(path),
        opt(cell.boot),
        opt(cell.user_target),
        cell.trusted_core,
    )
}

pub(crate) fn render() -> String {
    let rows: Vec<String> = catalog::CELLS.iter().map(row).collect();
    let prefixes: Vec<String> = catalog::SANDBOX_PREFIXES
        .iter()
        .map(|p| format!("\"{p}\""))
        .collect();
    let ids: Vec<String> = ETHERNET_DRIVER_IDS
        .iter()
        .map(|(vendor, device, path)| {
            format!("    {{\"vendor\": {vendor}, \"device\": {device}, \"path\": \"{path}\"}}")
        })
        .collect();
    let sandbox_request = caps(&catalog::request("/apps/x"));
    let unlisted_request = caps(&catalog::request("/bin/not-in-catalog"));
    format!(
        "{{\n  \"source\": \"kernel/src/catalog.rs (generated by the catalog_export host test)\",\n  \"sandbox_prefixes\": [{}],\n  \"sandbox_request\": {sandbox_request},\n  \"unlisted_request\": {unlisted_request},\n  \"cells\": [\n{}\n  ],\n  \"ethernet_driver_ids\": [\n{}\n  ]\n}}\n",
        prefixes.join(", "),
        rows.join(",\n"),
        ids.join(",\n"),
    )
}

#[test]
fn catalog_export() {
    extern crate std;
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../scripts/catalog.generated.json");
    let text = render();
    if std::env::var_os("CELLOS_CATALOG_WRITE").is_some() {
        std::fs::write(&path, &text).expect("write scripts/catalog.generated.json");
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == text,
        "scripts/catalog.generated.json is stale; regenerate with CELLOS_CATALOG_WRITE=1"
    );
}
