static void write_registers(const uint8_t *regs)
{
    outb(0x3C2, *regs);
    regs++;

    for (uint8_t i = 0; i < 5U; i++) {
        outb(0x3C4, i);
        outb(0x3C5, *regs);
        regs++;
    }

    outb(0x3D4, 0x03);
    outb(0x3D5, (uint8_t)(inb(0x3D5) | 0x80U));
    outb(0x3D4, 0x11);
    outb(0x3D5, (uint8_t)(inb(0x3D5) & 0x7FU));

    for (uint8_t i = 0; i < 25U; i++) {
        outb(0x3D4, i);
        outb(0x3D5, *regs);
        regs++;
    }

    for (uint8_t i = 0; i < 9U; i++) {
        outb(0x3CE, i);
        outb(0x3CF, *regs);
        regs++;
    }

    for (uint8_t i = 0; i < 21U; i++) {
        (void)inb(0x3DA);
        outb(0x3C0, i);
        outb(0x3C0, *regs);
        regs++;
    }

    (void)inb(0x3DA);
    outb(0x3C0, 0x20);
}

static void set_palette_entry(uint8_t index, uint8_t r, uint8_t g, uint8_t b)
{
    outb(0x3C8, index);
    outb(0x3C9, r);
    outb(0x3C9, g);
    outb(0x3C9, b);
}

static void init_palette(void)
{
    set_palette_entry(0, 0, 0, 0);
    set_palette_entry(1, 0, 0, 42);
    set_palette_entry(2, 0, 42, 0);
    set_palette_entry(4, 42, 0, 0);
    set_palette_entry(5, 42, 0, 42);
    set_palette_entry(6, 42, 21, 0);
    set_palette_entry(7, 42, 42, 42);
    set_palette_entry(8, 21, 21, 21);
    set_palette_entry(9, 21, 21, 63);
    set_palette_entry(14, 63, 63, 21);
    set_palette_entry(15, 63, 63, 63);
}

void vga_init(void)
{
    write_registers(mode13_registers);
    init_palette();
    vga_clear(0);
    vga_present();
}

void vga_put_pixel(int x, int y, uint8_t color)
{
    if (x < 0 || x >= VGA_WIDTH || y < 0 || y >= VGA_HEIGHT) {
        return;
    }

    backbuffer[(y * VGA_WIDTH) + x] = color;
}

void vga_fill_rect(int x, int y, int w, int h, uint8_t color)
{
    int x0 = x;
    int y0 = y;
    int x1 = x + w;
    int y1 = y + h;

    if (x0 < 0) {
        x0 = 0;
    }
    if (y0 < 0) {
        y0 = 0;
    }
    if (x1 > VGA_WIDTH) {
        x1 = VGA_WIDTH;
    }
    if (y1 > VGA_HEIGHT) {
        y1 = VGA_HEIGHT;
    }

    for (int yy = y0; yy < y1; yy++) {
        uint32_t offset = (uint32_t)((yy * VGA_WIDTH) + x0);
        for (int xx = x0; xx < x1; xx++) {
            backbuffer[offset] = color;
            offset++;
        }
    }
}

void vga_draw_char(int x, int y, char c, uint8_t fg, uint8_t bg)
{
    unsigned char uc = (unsigned char)c;
    uint8_t index = (uc >= 32U && uc <= 127U) ? (uint8_t)(uc - 32U) : (uint8_t)('?' - 32);

    for (int row = 0; row < 8; row++) {
        uint8_t bits = font[index][row];
        for (int col = 0; col < 8; col++) {
            uint8_t color = ((bits & (uint8_t)(0x80U >> col)) != 0U) ? fg : bg;
            vga_put_pixel(x + col, y + row, color);
        }
    }
}

void vga_draw_string(int x, int y, const char *text, uint8_t fg, uint8_t bg)
{
    int cursor_x = x;
    while (*text != '\0') {
        vga_draw_char(cursor_x, y, *text, fg, bg);
        cursor_x += 8;
        text++;
    }
}

void vga_draw_number(int x, int y, uint32_t value, uint8_t fg, uint8_t bg)
{
    char digits[11];
    uint32_t count = 0;

    if (value == 0U) {
        vga_draw_char(x, y, '0', fg, bg);
        return;
    }

    while (value != 0U && count < sizeof(digits)) {
        digits[count] = (char)('0' + (value % 10U));
        value /= 10U;
        count++;
    }

    for (uint32_t i = 0; i < count; i++) {
        vga_draw_char(x + ((int)i * 8), y, digits[count - i - 1U], fg, bg);
    }
}

void vga_clear(uint8_t color)
{
    vga_fill_rect(0, 0, VGA_WIDTH, VGA_HEIGHT, color);
}

void vga_present(void)
{
    uint32_t guard = 100000U;
    while (((inb(0x3DA) & 0x08U) != 0U) && guard != 0U) {
        guard--;
    }

    guard = 100000U;
    while (((inb(0x3DA) & 0x08U) == 0U) && guard != 0U) {
        guard--;
    }

    for (uint32_t i = 0; i < VGA_SIZE; i++) {
        VGA_MEMORY[i] = backbuffer[i];
    }
}
